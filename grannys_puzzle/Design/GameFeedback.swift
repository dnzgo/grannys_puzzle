import SwiftUI

/// Moments in the game that the player should feel and hear. View models
/// report these; the views turn them into a vibration and a sound with
/// `.gameFeedback(_:)`.
///
/// Keeping "what happened" (here) apart from "how it feels and sounds"
/// (`haptic` below, `sound` in Audio/SoundEffects.swift) means the feel of
/// the whole game is tuned in one place, and view models never touch a
/// haptics or audio API, so they stay easy to test. It also means a new
/// moment can't get a vibration but forget its sound: both switches below
/// are exhaustive, so the compiler asks for each.
///
/// CaseIterable so the sound player can load every moment's sounds at
/// launch (generated by Swift, so a new case can't be left out of it).
enum FeedbackEvent: Equatable, CaseIterable {
    /// Tapping a cell or moving between clues.
    case select
    /// A letter placed from the tray: the keyboard click.
    case letterPlaced
    case letterErased
    /// The cat or grandma filling in letters.
    case reveal
    case levelPassed
    case levelFailed
    /// A finished knitted item revealed.
    case itemKnitted
    /// The jar's treat revealed.
    case jarOpened
    /// Helpers earned by watching a video.
    case helperEarned
    /// A yarn ball dropping into grandma's bag after a level. Soft: up to
    /// three come in quick succession.
    case yarnLanded
    /// A tapped jar wobbling before it opens.
    case jarShaken
    /// A helper from a jar arriving at its counter. Soft, like the yarn.
    case prizeLanded
    /// Submit tapped and the board accepted for judging.
    case submitted
    /// A finished family member's wardrobe shaking before it's swapped.
    case wardrobeShaken
    /// One group of cells lighting green or red after Submit. The lightest
    /// tick of all: a wave can have fifteen of them in a second.
    case cellsJudged

    /// How each moment feels. Small and frequent actions get the lightest
    /// taps; only real outcomes get the stronger, patterned ones. If every
    /// tap buzzed hard, the big moments would stop standing out.
    ///
    /// Nil: a moment that's heard but not felt. Submit is one: the judging
    /// wave right after it already ticks, and a buzz on top would blur them.
    var haptic: SensoryFeedback? {
        switch self {
        case .submitted: nil
        case .select, .letterErased: .selection
        case .letterPlaced, .yarnLanded, .prizeLanded: .impact(flexibility: .soft, intensity: 0.6)
        case .jarShaken: .impact(weight: .light)
        case .cellsJudged: .impact(flexibility: .soft, intensity: 0.35)
        case .reveal, .wardrobeShaken: .impact(weight: .medium)
        case .levelPassed, .itemKnitted, .jarOpened, .helperEarned: .success
        case .levelFailed: .warning
        }
    }
}

/// One moment to play. The id makes two identical events in a row (two
/// letters typed) count as two changes, so both of them buzz and click.
struct FeedbackSignal: Equatable {
    let event: FeedbackEvent
    let id: Int
}

private struct GameFeedback: ViewModifier {
    let signal: FeedbackSignal?
    // The Haptics and Sounds switches in Settings write these same keys.
    // Each is checked separately: plenty of players want one without the
    // other (sound off on the bus, but still the buzz).
    @AppStorage(ToggleSetting.haptics.key) private var hapticsOn = ToggleSetting.haptics.defaultValue
    @AppStorage(ToggleSetting.sound.key) private var soundOn = ToggleSetting.sound.defaultValue
    /// Nil in previews, which then stay silent.
    @Environment(SoundPlayer.self) private var sounds: SoundPlayer?

    func body(content: Content) -> some View {
        content
            // Returning nil plays nothing: that's how the setting switches it off.
            .sensoryFeedback(trigger: signal) { _, new in
                guard hapticsOn, let new else { return nil }
                return new.event.haptic
            }
            .onChange(of: signal) { _, new in
                guard soundOn, let new else { return }
                sounds?.play(new.event.sound)
            }
    }
}

extension View {
    /// Plays the vibration and the sound for each new signal, each only if
    /// the player has it switched on.
    func gameFeedback(_ signal: FeedbackSignal?) -> some View {
        modifier(GameFeedback(signal: signal))
    }
}
